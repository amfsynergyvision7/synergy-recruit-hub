DO $before$DECLARE n int;BEGIN SELECT count(*) INTO n FROM pg_proc fn JOIN pg_namespace ns ON ns.oid=fn.pronamespace WHERE ns.nspname='public' AND fn.prosecdef AND has_function_privilege('anon',fn.oid,'EXECUTE'); IF n<>16 THEN RAISE EXCEPTION 'before expected16 got %',n; END IF; END $before$;

DO $priv$ DECLARE rec record;total int:=0;authenticated_count int:=0; BEGIN
FOR rec IN SELECT fn.oid,fn.proname,fn.proconfig FROM pg_proc fn JOIN pg_namespace ns ON ns.oid=fn.pronamespace WHERE ns.nspname='public' AND fn.prosecdef LOOP
 total:=total+1;
 IF has_function_privilege('anon',rec.oid,'EXECUTE') THEN RAISE EXCEPTION 'anon EXECUTE %',rec.proname; END IF;
 IF NOT has_function_privilege('service_role',rec.oid,'EXECUTE') THEN RAISE EXCEPTION 'service cannot execute %',rec.proname; END IF;
 IF has_function_privilege('authenticated',rec.oid,'EXECUTE') THEN
  authenticated_count:=authenticated_count+1;
  IF rec.proname NOT IN('get_user_role','has_role','is_approved') THEN RAISE EXCEPTION 'auth unexpected EXECUTE %',rec.proname; END IF;
 ELSE IF rec.proname IN('get_user_role','has_role','is_approved') THEN RAISE EXCEPTION 'auth helper lost %',rec.proname; END IF; END IF;
 IF rec.proname IN('set_assigned_recruiter','track_stage_changes') AND NOT EXISTS (SELECT 1 FROM unnest(rec.proconfig) AS config WHERE config LIKE 'search_path=pg_catalog%') THEN RAISE EXCEPTION 'mutable search_path %',rec.proname; END IF;
END LOOP;
IF total<>16 OR authenticated_count<>3 THEN RAISE EXCEPTION 'function counts %, %',total,authenticated_count; END IF;
END $priv$;
